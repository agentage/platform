import { access, cp, mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, isAbsolute, join, normalize, sep } from 'node:path';
import { type ExtensionPackage } from '../manifest/manifest.schema.js';
import { entryOf, hasPostgres } from '../manifest/parts.js';
import { type ImagePartKind } from '../manifest/primitives.schema.js';
import { OPENAPI_FILE } from '../discovery/openapi.js';
import { serverPartRecipe } from './recipe.js';

export const RECORD_FILE = 'agentage-extension.json';

// The api image's migrate entry: `node dist/store/migrate.js` in /app runs the kit's migration runner.
export const MIGRATE_SHIM =
  "// Generated by @agentage/extension build.\nimport '@agentage/extension/migrate';\n";

const dependencySpecs = (pkg: ExtensionPackage): string[] => {
  const deps = (pkg as { dependencies?: unknown }).dependencies;
  if (typeof deps !== 'object' || deps === null) return [];
  return Object.values(deps).filter((spec): spec is string => typeof spec === 'string');
};

// `file:` tarball dependencies travel into the deps stage at the same relative path.
export const localTarballs = (pkg: ExtensionPackage): string[] =>
  dependencySpecs(pkg)
    .filter((spec) => spec.startsWith('file:') && spec.endsWith('.tgz'))
    .map((spec) => normalize(spec.slice('file:'.length)))
    .map((path) => {
      if (isAbsolute(path) || path.startsWith('..')) {
        throw new Error(`local dependency ${path} must live inside the package folder`);
      }
      return path;
    });

export const exists = (path: string): Promise<boolean> =>
  access(path).then(
    () => true,
    () => false
  );

const copyInto = async (from: string, to: string): Promise<void> => {
  await mkdir(dirname(to), { recursive: true });
  await cp(from, to, { recursive: true });
};

const copyDeps = async (dir: string, root: string, pkg: ExtensionPackage): Promise<void> => {
  if (!(await exists(join(dir, 'package-lock.json')))) {
    throw new Error('package-lock.json is missing: the image installs with npm ci');
  }
  await copyInto(join(dir, 'package.json'), join(root, 'deps', 'package.json'));
  await copyInto(join(dir, 'package-lock.json'), join(root, 'deps', 'package-lock.json'));
  for (const path of localTarballs(pkg)) await copyInto(join(dir, path), join(root, 'deps', path));
};

// The api image runs the migrate job, so it alone carries the migrations; seeds never ship.
const migrates = (pkg: ExtensionPackage, part: ImagePartKind): boolean =>
  part === 'api' && hasPostgres(pkg);

// What a part image carries: its own dist/{part}, the shared dist/lib, and for api the migrations.
export const appPaths = async (dir: string, pkg: ExtensionPackage, part: ImagePartKind) => {
  const paths = ['package.json', join('dist', part)];
  if (part === 'api' && (await exists(join(dir, OPENAPI_FILE)))) paths.push(OPENAPI_FILE);
  if (await exists(join(dir, 'dist', 'lib'))) paths.push(join('dist', 'lib'));
  if (migrates(pkg, part) && (await exists(join(dir, 'migrations')))) paths.push('migrations');
  return paths;
};

const copyApp = async (dir: string, root: string, pkg: ExtensionPackage, part: ImagePartKind) => {
  for (const path of await appPaths(dir, pkg, part))
    await copyInto(join(dir, path), join(root, 'app', path));
  if (migrates(pkg, part)) {
    await mkdir(join(root, 'app', 'dist', 'store'), { recursive: true });
    await writeFile(join(root, 'app', 'dist', 'store', 'migrate.js'), MIGRATE_SHIM);
  }
};

// ui is a bundle, not an entry: the widget bundler writes dist/ui/widgets.json beside it.
const builtFile = (pkg: ExtensionPackage, part: ImagePartKind): string =>
  normalize(part === 'ui' ? './dist/ui/widgets.json' : entryOf(pkg, part));

// The image carries dist/ only, so an entry outside it, or never built, would not start.
export const assertBuilt = async (dir: string, pkg: ExtensionPackage, part: ImagePartKind) => {
  const file = builtFile(pkg, part);
  if (!file.startsWith(`dist${sep}${part}${sep}`)) {
    throw new Error(`the ${part} entry ${file} is not in dist/${part}/`);
  }
  if (!(await exists(join(dir, file)))) {
    throw new Error(`${file} not found: the package build must write the ${part} part there`);
  }
};

// A clean build context per part: the manifest, the lockfile, local tarballs and the part's files.
export const stageContext = async (
  dir: string,
  pkg: ExtensionPackage,
  part: ImagePartKind,
  tmpRoot: string = tmpdir()
): Promise<string> => {
  await assertBuilt(dir, pkg, part);
  const root = await mkdtemp(join(tmpRoot, `agentage-${pkg.agentage.id}-${part}-`));
  await copyDeps(dir, root, pkg);
  await copyApp(dir, root, pkg, part);
  await writeFile(join(root, 'Dockerfile'), serverPartRecipe(part));
  return root;
};
