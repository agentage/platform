// Compiles src/ds/widget.css with Tailwind v4 into src/ds/styles.generated.ts (two strings).
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import tailwind from '@tailwindcss/postcss';
import postcss from 'postcss';

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const input = join(pkgDir, 'src/ds/widget.css');
const output = join(pkgDir, 'src/ds/styles.generated.ts');
const DS_FILES = ['button.js', 'button.variants.js', 'card.js', 'card-base.js'];

const dsSources = () => {
  const dir = dirname(fileURLToPath(import.meta.resolve('@agentage/design-system/button')));
  return DS_FILES.map((file) => `@source "${join(dir, file)}";`).join('\n');
};

const isRootRule = (node) => node.type === 'rule' && node.selectors.includes(':root');
const LIGHT = /^html\[data-theme=['"]?light['"]?\]$/;
const SYSTEM = /^html\[data-theme=['"]?system['"]?\]$/;

// Shadow trees: @property out to the document, :root also as :host, the system light theme on :host.
const toShadow = (root) => {
  const properties = [];
  root.walkAtRules('property', (rule) => {
    properties.push(rule.toString());
    rule.remove();
  });
  root.walkRules((rule) => {
    if (LIGHT.test(rule.selector)) return void rule.remove();
    if (SYSTEM.test(rule.selector)) rule.selector = ':host';
    else if (isRootRule(rule) && !rule.selectors.includes(':host'))
      rule.selectors = [...rule.selectors, ':host'];
  });
  return { widgetCss: root.toString(), propertyCss: properties.join('') };
};

const source = `${await readFile(input, 'utf8')}\n${dsSources()}\n`;
const tw = tailwind({ base: pkgDir, optimize: { minify: true } });
const compiled = await postcss([tw]).process(source, { from: input });
const { widgetCss, propertyCss } = toShadow(postcss.parse(compiled.css));
const lines = [
  '// Generated by scripts/build-css.mjs from src/ds/widget.css; never edit by hand.',
  `export const widgetCss = ${JSON.stringify(widgetCss)};`,
  `export const propertyCss = ${JSON.stringify(propertyCss)};`,
  '',
];
await writeFile(output, lines.join('\n'));
console.log(`css  ${output}  ${widgetCss.length + propertyCss.length} bytes`);
